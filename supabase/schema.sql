-- BasuReport server database. Run in Supabase SQL Editor before starting Flask.
-- The Flask server uses a private database connection, not the browser Data API.
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fullname VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    last_seen_at TIMESTAMP DEFAULT NULL
);
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS last_seen_at TIMESTAMP DEFAULT NULL;

CREATE TABLE IF NOT EXISTS public.reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_code VARCHAR(40) NOT NULL UNIQUE,
    resident_email VARCHAR(255) NOT NULL,
    fullname VARCHAR(150) NOT NULL,
    contact_phone VARCHAR(30) NOT NULL DEFAULT '',
    report_date VARCHAR(30) NOT NULL,
    report_time VARCHAR(30) NOT NULL,
    sitio VARCHAR(255) NOT NULL,
    description TEXT,
    image VARCHAR(255) NOT NULL,
    clean_image VARCHAR(255),
    priority VARCHAR(20) NOT NULL DEFAULT 'Normal',
    status VARCHAR(30) NOT NULL DEFAULT 'Pending',
    created_at TIMESTAMP NOT NULL,
    completed_at TIMESTAMP,
    deleted_at TIMESTAMP,
    rating SMALLINT CHECK (rating BETWEEN 1 AND 5),
    feedback TEXT,
    feedback_at TIMESTAMP
);
ALTER TABLE public.reports ADD COLUMN IF NOT EXISTS contact_phone VARCHAR(30) NOT NULL DEFAULT '';
ALTER TABLE public.reports ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMP;
ALTER TABLE public.reports ADD COLUMN IF NOT EXISTS rating SMALLINT CHECK (rating BETWEEN 1 AND 5);
ALTER TABLE public.reports ADD COLUMN IF NOT EXISTS feedback TEXT;
ALTER TABLE public.reports ADD COLUMN IF NOT EXISTS feedback_at TIMESTAMP;
CREATE INDEX IF NOT EXISTS idx_report_email ON public.reports (resident_email);
CREATE INDEX IF NOT EXISTS idx_report_status ON public.reports (status);
CREATE INDEX IF NOT EXISTS idx_report_created ON public.reports (created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS public.notifications (
    id VARCHAR(64) PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    message TEXT NOT NULL,
    type VARCHAR(50) NOT NULL,
    report_id VARCHAR(40),
    created_at TIMESTAMP NOT NULL,
    is_read SMALLINT NOT NULL DEFAULT 0 CHECK (is_read IN (0, 1))
);
CREATE INDEX IF NOT EXISTS idx_notification_created ON public.notifications (created_at DESC);

CREATE TABLE IF NOT EXISTS public.announcements (
    id VARCHAR(64) PRIMARY KEY,
    title VARCHAR(160) NOT NULL,
    message TEXT NOT NULL,
    created_by VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_announcement_created ON public.announcements (created_at DESC);

CREATE TABLE IF NOT EXISTS public.resident_login_otps (
    email VARCHAR(255) PRIMARY KEY,
    otp_hash VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    attempts INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS public.resident_password_reset_otps (
    email VARCHAR(255) PRIMARY KEY,
    otp_hash VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    attempts INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL
);

-- Password hashes, OTP hashes and private reports must not be exposed through
-- Supabase's anonymous/authenticated browser roles. Server-side postgres access
-- bypasses RLS; application routes enforce resident ownership/admin permissions.
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.announcements ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.resident_login_otps ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.resident_password_reset_otps ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.users, public.reports, public.notifications, public.announcements,
    public.resident_login_otps, public.resident_password_reset_otps FROM PUBLIC;
DO $$
DECLARE api_role TEXT;
BEGIN
    FOREACH api_role IN ARRAY ARRAY['anon', 'authenticated'] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = api_role) THEN
            EXECUTE format('REVOKE ALL ON public.users, public.reports, public.notifications, public.announcements, public.resident_login_otps, public.resident_password_reset_otps FROM %I', api_role);
            EXECUTE format('REVOKE ALL ON SEQUENCE public.users_id_seq, public.reports_id_seq FROM %I', api_role);
        END IF;
    END LOOP;
END $$;
