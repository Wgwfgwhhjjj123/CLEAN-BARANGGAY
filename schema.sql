-- BasuReport - Supabase PostgreSQL schema
-- Matches the columns that app.py reads and writes. Safe to run many
-- times: it creates missing tables and adds missing columns only.
-- Run in: Supabase > SQL Editor > New query > Run
-- (Flask also runs this file at startup.)
-- =====================================================================

-- ---------- users (residents) ----------
CREATE TABLE IF NOT EXISTS users (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fullname     VARCHAR(150) NOT NULL,
    email        VARCHAR(255) NOT NULL,
    password     VARCHAR(255) NOT NULL,          -- Werkzeug hash, never plain text
    last_seen_at TIMESTAMP DEFAULT NULL
);
ALTER TABLE users ADD COLUMN IF NOT EXISTS last_seen_at TIMESTAMP DEFAULT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_lower ON users (LOWER(email));

-- ---------- reports ----------
CREATE TABLE IF NOT EXISTS reports (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_code    VARCHAR(40)  NOT NULL UNIQUE,
    resident_email VARCHAR(255) NOT NULL,
    fullname       VARCHAR(150) NOT NULL,
    contact_phone  VARCHAR(30)  NOT NULL DEFAULT '',
    report_date    VARCHAR(30)  NOT NULL,
    report_time    VARCHAR(30)  NOT NULL,
    sitio          VARCHAR(255) NOT NULL,
    description    TEXT,
    image          VARCHAR(255) NOT NULL,        -- BEFORE cleaning photo filename
    clean_image    VARCHAR(255) DEFAULT NULL,    -- AFTER cleaning photo filename
    priority       VARCHAR(20)  NOT NULL DEFAULT 'Normal',
    status         VARCHAR(30)  NOT NULL DEFAULT 'Pending',
    created_at     TIMESTAMP    NOT NULL,
    completed_at   TIMESTAMP    DEFAULT NULL,
    deleted_at     TIMESTAMP    DEFAULT NULL,
    rating         SMALLINT     DEFAULT NULL,    -- 1-5 stars from the resident
    feedback       TEXT         DEFAULT NULL,
    feedback_at    TIMESTAMP    DEFAULT NULL
);
ALTER TABLE reports ADD COLUMN IF NOT EXISTS contact_phone VARCHAR(30) NOT NULL DEFAULT '';
ALTER TABLE reports ADD COLUMN IF NOT EXISTS clean_image   VARCHAR(255) DEFAULT NULL;
ALTER TABLE reports ADD COLUMN IF NOT EXISTS completed_at  TIMESTAMP DEFAULT NULL;
ALTER TABLE reports ADD COLUMN IF NOT EXISTS deleted_at    TIMESTAMP DEFAULT NULL;
ALTER TABLE reports ADD COLUMN IF NOT EXISTS rating        SMALLINT DEFAULT NULL;
ALTER TABLE reports ADD COLUMN IF NOT EXISTS feedback      TEXT DEFAULT NULL;
ALTER TABLE reports ADD COLUMN IF NOT EXISTS feedback_at   TIMESTAMP DEFAULT NULL;
CREATE INDEX IF NOT EXISTS idx_report_email   ON reports (resident_email);
CREATE INDEX IF NOT EXISTS idx_report_status  ON reports (status);
CREATE INDEX IF NOT EXISTS idx_report_created ON reports (created_at DESC);

-- ---------- notifications (newest first via index) ----------
CREATE TABLE IF NOT EXISTS notifications (
    id         VARCHAR(64)  PRIMARY KEY,
    title      VARCHAR(200) NOT NULL,
    message    TEXT         NOT NULL,
    type       VARCHAR(50)  NOT NULL,
    report_id  VARCHAR(40)  DEFAULT NULL,         -- links to reports.report_code
    created_at TIMESTAMP    NOT NULL,
    is_read    SMALLINT     NOT NULL DEFAULT 0    -- 0 = unread, 1 = read (app uses 0/1)
);
CREATE INDEX IF NOT EXISTS idx_notification_created ON notifications (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_notification_report  ON notifications (report_id);

-- ---------- announcements ----------
CREATE TABLE IF NOT EXISTS announcements (
    id         VARCHAR(64)  PRIMARY KEY,
    title      VARCHAR(160) NOT NULL,
    message    TEXT         NOT NULL,
    created_by VARCHAR(255) NOT NULL,
    created_at TIMESTAMP    NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_announcement_created ON announcements (created_at DESC);

-- ---------- OTP tables (hashed codes) ----------
CREATE TABLE IF NOT EXISTS resident_login_otps (
    email      VARCHAR(255) PRIMARY KEY,
    otp_hash   VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP    NOT NULL,
    attempts   INTEGER      NOT NULL DEFAULT 0,
    created_at TIMESTAMP    NOT NULL
);
CREATE TABLE IF NOT EXISTS resident_password_reset_otps (
    email      VARCHAR(255) PRIMARY KEY,
    otp_hash   VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP    NOT NULL,
    attempts   INTEGER      NOT NULL DEFAULT 0,
    created_at TIMESTAMP    NOT NULL
);

-- ---------- Security: private tables, Flask connects as owner ----------
ALTER TABLE users                        ENABLE ROW LEVEL SECURITY;
ALTER TABLE reports                      ENABLE ROW LEVEL SECURITY;
ALTER TABLE notifications                ENABLE ROW LEVEL SECURITY;
ALTER TABLE announcements                ENABLE ROW LEVEL SECURITY;
ALTER TABLE resident_login_otps          ENABLE ROW LEVEL SECURITY;
ALTER TABLE resident_password_reset_otps ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON users, reports, notifications, announcements,
                  resident_login_otps, resident_password_reset_otps FROM anon;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON users, reports, notifications, announcements,
                  resident_login_otps, resident_password_reset_otps FROM authenticated;
  END IF;
END
$$;
