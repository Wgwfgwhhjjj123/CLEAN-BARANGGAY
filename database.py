"""Database connection for Supabase PostgreSQL."""
import os
from pathlib import Path

import psycopg
from psycopg.rows import dict_row
from psycopg.conninfo import conninfo_to_dict

INTEGRITY_ERRORS = (psycopg.IntegrityError,)


def postgres_url():
    return os.getenv("SUPABASE_DB_URL", "").strip()


def using_postgres():
    return bool(postgres_url())


def get_db_connection():
    if not using_postgres():
        raise RuntimeError(
            "SUPABASE_DB_URL is not set. Add the Supabase PostgreSQL "
            "session-pooler URI to the environment."
        )

    sslmode = conninfo_to_dict(postgres_url()).get("sslmode", "require")
    if sslmode not in {"require", "verify-ca", "verify-full"}:
        sslmode = "require"
    return psycopg.connect(
        postgres_url(), sslmode=sslmode, connect_timeout=10,
        row_factory=dict_row, prepare_threshold=None,
    )


# Repairs for a users table that already existed before this version.
USERS_REPAIR_SQL = """
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fullname VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    last_seen_at TIMESTAMP DEFAULT NULL
);

ALTER TABLE users ADD COLUMN IF NOT EXISTS last_seen_at TIMESTAMP DEFAULT NULL;

-- Hash strings are long; make sure the column can hold them.
ALTER TABLE users ALTER COLUMN password TYPE VARCHAR(255);

-- Make sure id numbers itself (fixes: null value in column "id").
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'users'
          AND column_name = 'id'
          AND column_default IS NULL AND is_identity = 'NO'
    ) THEN
        ALTER TABLE users ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
        PERFORM setval(
            pg_get_serial_sequence('users', 'id'),
            COALESCE((SELECT MAX(id) FROM users), 0) + 1, false
        );
    END IF;
END $$;
"""


def init_postgres_db():
    """Create tables from supabase/schema.sql, then repair the users table."""
    schema = Path(__file__).with_name("supabase").joinpath("schema.sql").read_text()
    connection = get_db_connection()
    try:
        with connection.cursor() as cursor:
            cursor.execute(schema)
            cursor.execute(USERS_REPAIR_SQL)
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def otp_upsert_query(table):
    if table not in {"resident_login_otps", "resident_password_reset_otps"}:
        raise ValueError("Unknown OTP table")
    return f"""INSERT INTO {table}
        (email, otp_hash, expires_at, attempts, created_at)
        VALUES (%s, %s, %s, 0, %s)
        ON CONFLICT (email) DO UPDATE SET
            otp_hash = EXCLUDED.otp_hash, expires_at = EXCLUDED.expires_at,
            attempts = 0, created_at = EXCLUDED.created_at"""
